export function searchManual(query: string): ManualChapter[] {
  const value = query.trim().toLocaleLowerCase();
  if (!value) return manualChapters;
  return manualChapters.filter(chapter => [chapter.title, chapter.summary,
    ...chapter.blocks.flatMap(block => [block.title, ...(block.paragraphs ?? []), ...(block.steps ?? []), ...(block.bullets ?? []),
      ...(block.table?.headers ?? []), ...(block.table?.rows.flat() ?? []), block.callout?.title ?? '', block.callout?.text ?? '']),
  ].join('\n').toLocaleLowerCase().includes(value));
}
